// Generates docs/mcp/tools.md from the live server's tools/list response, so
// the reference cannot drift from the implementation.
//
//   node test/gen-tools-doc.mjs > ../../docs/mcp/tools.md

import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const transport = new StdioClientTransport({
  command: 'node',
  args: [path.join(here, '..', 'src', 'index.mjs')],
  env: { ...process.env, MAME_BINARY: '/nonexistent' },
});
const client = new Client({ name: 'docgen', version: '1.0.0' }, { capabilities: {} });
await client.connect(transport);
const { tools } = await client.listTools();

const GROUPS = [
  ['session', 'Session lifecycle'],
  ['machine', 'Machine inspection'],
  ['exec',    'Execution control'],
  ['bp',      'Breakpoints'],
  ['wp',      'Watchpoints'],
  ['rp',      'Registerpoints'],
  ['mem',     'Memory'],
  ['cpu',     'CPU state and disassembly'],
  ['sym',     'Expressions'],
  ['annot',   'Annotations'],
  ['video',   'Video'],
  ['audio',   'Audio'],
  ['input',   'Input'],
  ['state',   'Save states'],
  ['debug',   'Escape hatch and logs'],
];

const kind = (a = {}) =>
  a.readOnlyHint ? 'read-only' : (a.destructiveHint ? '**destructive**' : 'mutating');

const args = (schema) => {
  const props = schema?.properties || {};
  const req = new Set(schema?.required || []);
  const names = Object.keys(props);
  if (!names.length) return '_(no arguments)_';
  return names.map((n) => {
    const p = props[n];
    let t = p.type || (p.anyOf ? p.anyOf.map((x) => x.type).filter(Boolean).join('\\|') : '')
          || (p.enum ? p.enum.map((v) => `"${v}"`).join('\\|') : 'any');
    if (p.enum && !p.type) t = p.enum.map((v) => `"${v}"`).join('\\|');
    return `\`${n}\`${req.has(n) ? '' : '?'}: ${t}${p.description ? ' — ' + p.description : ''}`;
  }).map((s) => '  - ' + s).join('\n');
};

let out = `<!-- GENERATED by mcp-server/test/gen-tools-doc.mjs -- do not edit by hand -->
# mame-mcp tool reference

${tools.length} tools. Generated from the running server's \`tools/list\`.

Legend: **read-only** never changes emulation state · *mutating* changes it safely ·
***destructive*** can corrupt the running program (memory writes, raw debugger commands).

`;

const seen = new Set();
for (const [prefix, title] of GROUPS) {
  const group = tools.filter((t) => t.name.startsWith(prefix + '.'));
  if (!group.length) continue;
  out += `\n## ${title}\n\n`;
  for (const t of group.sort((a, b) => a.name.localeCompare(b.name))) {
    seen.add(t.name);
    out += `### \`${t.name}\`\n\n`;
    out += `*${kind(t.annotations)}* — ${t.description}\n\n`;
    out += `${args(t.inputSchema)}\n\n`;
  }
}
const rest = tools.filter((t) => !seen.has(t.name));
if (rest.length) {
  out += `\n## Other\n\n`;
  for (const t of rest) out += `### \`${t.name}\`\n\n${t.description}\n\n`;
}

process.stdout.write(out);
await client.close();
process.exit(0);
